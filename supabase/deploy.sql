-- Agua y Lluvia · esquema completo para un proyecto Supabase vacío.
-- Ejecutar en Supabase > SQL Editor > New query.
-- No inserta reportes, alertas ni dispositivos sintéticos.

begin;

create schema if not exists extensions;
create extension if not exists postgis with schema extensions;

-- Si PostGIS ya existía, debe estar en `extensions` para evitar exponer sus
-- tablas internas mediante la Data API de Supabase.
do $$
declare
    esquema_postgis text;
begin
    select n.nspname
      into esquema_postgis
      from pg_extension e
      join pg_namespace n on n.oid = e.extnamespace
     where e.extname = 'postgis';

    if esquema_postgis is distinct from 'extensions' then
        raise exception 'PostGIS está instalado en %, no en extensions', esquema_postgis;
    end if;
end
$$;

create table if not exists public.colonias (
    id integer generated by default as identity primary key,
    nombre varchar(200) not null,
    municipio varchar(100) not null,
    geom extensions.geometry(MultiPolygon, 4326) not null,
    vulnerabilidad double precision not null,
    vulnerabilidad_fuente varchar(20) not null,
    constraint ck_colonias_vulnerabilidad
        check (vulnerabilidad between 0 and 1)
);

create index if not exists ix_colonias_nombre
    on public.colonias (nombre);
create index if not exists idx_colonias_geom
    on public.colonias using gist (geom);

create table if not exists public.reportes (
    id integer generated by default as identity primary key,
    categoria varchar(40) not null,
    severidad integer not null,
    descripcion text,
    lat double precision not null,
    lon double precision not null,
    ubicacion extensions.geometry(Point, 4326) not null,
    colonia_id integer references public.colonias(id),
    foto_url varchar(500),
    dispositivo_id varchar(200),
    origen varchar(20) not null,
    estado varchar(20) not null,
    creado_en timestamptz not null,
    expira_en timestamptz not null,
    constraint ck_reportes_categoria
        check (categoria in ('inundacion', 'encharcamiento', 'alcantarilla', 'fuga', 'sin_agua')),
    constraint ck_reportes_severidad check (severidad between 1 and 3),
    constraint ck_reportes_lat check (lat between -90 and 90),
    constraint ck_reportes_lon check (lon between -180 and 180),
    constraint ck_reportes_origen check (origen in ('app', 'panel', 'seed')),
    constraint ck_reportes_estado check (estado in ('activo', 'resuelto')),
    constraint ck_reportes_descripcion_longitud
        check (descripcion is null or length(descripcion) <= 500)
);

create index if not exists ix_reportes_categoria
    on public.reportes (categoria);
create index if not exists ix_reportes_colonia_id
    on public.reportes (colonia_id);
create index if not exists ix_reportes_estado
    on public.reportes (estado);
create index if not exists ix_reportes_expira_en
    on public.reportes (expira_en);
create index if not exists idx_reportes_ubicacion
    on public.reportes using gist (ubicacion);
create index if not exists ix_reportes_activos_recientes
    on public.reportes (estado, expira_en, creado_en);

create table if not exists public.riesgo_colonias (
    colonia_id integer primary key
        references public.colonias(id) on delete cascade,
    valor double precision not null,
    nivel varchar(20) not null,
    motivo varchar(40),
    componentes json not null,
    actualizado_en timestamptz not null,
    ultima_alerta_en timestamptz
);

create table if not exists public.alertas (
    id integer generated by default as identity primary key,
    colonia_id integer not null
        references public.colonias(id) on delete cascade,
    tipo varchar(40) not null,
    nivel varchar(20) not null,
    motivo varchar(40),
    texto text not null,
    estado varchar(20) not null,
    redactada_por varchar(20) not null,
    simulada boolean not null,
    creada_en timestamptz not null,
    aprobada_en timestamptz,
    constraint ck_alertas_tipo
        check (tipo in ('inundacion', 'encharcamiento', 'alcantarilla', 'fuga', 'sin_agua')),
    constraint ck_alertas_nivel check (nivel in ('bajo', 'medio', 'alto', 'critico')),
    constraint ck_alertas_estado check (estado in ('propuesta', 'aprobada', 'descartada')),
    constraint ck_alertas_redactada_por
        check (redactada_por in ('plantilla', 'llm', 'manual')),
    constraint ck_alertas_texto_longitud check (length(texto) between 10 and 1000)
);

create index if not exists ix_alertas_colonia_id
    on public.alertas (colonia_id);
create index if not exists ix_alertas_estado
    on public.alertas (estado);

create table if not exists public.dispositivos (
    id integer generated by default as identity primary key,
    token varchar(500) not null unique,
    colonia_id integer
        references public.colonias(id) on delete set null,
    plataforma varchar(20) not null,
    actualizado_en timestamptz not null,
    constraint ck_dispositivos_plataforma
        check (plataforma in ('android', 'ios', 'web'))
);

create index if not exists ix_dispositivos_colonia_id
    on public.dispositivos (colonia_id);

-- FastAPI es la única puerta de entrada. Los clientes anon/authenticated de
-- Supabase no reciben acceso SQL directo a estas tablas.
alter table public.colonias enable row level security;
alter table public.reportes enable row level security;
alter table public.riesgo_colonias enable row level security;
alter table public.alertas enable row level security;
alter table public.dispositivos enable row level security;

do $$
declare
    rol_objetivo text;
begin
    for rol_objetivo in
        select rolname from pg_roles where rolname in ('anon', 'authenticated')
    loop
        execute format(
            'revoke all on table public.colonias, public.reportes, public.riesgo_colonias, public.alertas, public.dispositivos from %I',
            rol_objetivo
        );
    end loop;
end
$$;

-- El esquema ya equivale al resultado de las migraciones 0001 + 0002.
create table if not exists public.alembic_version (
    version_num varchar(32) not null primary key
);

insert into public.alembic_version (version_num)
values ('0002')
on conflict (version_num) do nothing;

commit;

-- Verificación final. Debe mostrar PostGIS en extensions, versión 0002 y
-- cinco tablas de aplicación.
select e.extversion as postgis_version, n.nspname as postgis_schema
from pg_extension e
join pg_namespace n on n.oid = e.extnamespace
where e.extname = 'postgis';

select version_num from public.alembic_version;

select table_name
from information_schema.tables
where table_schema = 'public'
  and table_name in ('colonias', 'reportes', 'riesgo_colonias', 'alertas', 'dispositivos')
order by table_name;
